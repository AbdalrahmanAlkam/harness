"""The autonomous derivation kernel.

This is what makes research mode *research* rather than *verification*. Given a
topic, the kernel constructs machine-checkable propositions, emits a
self-adjudicating SymPy script for each, and lets the proof runner decide the
verdict from the exit code.

Two rules govern everything here:

1. **Never assert a result.** Every proposition is *constructed* from a
   definition inside the generated script, and SymPy decides whether it holds.
   The kernel has no hardcoded answers — only the ability to state a question
   exactly.
2. **A failed attempt is not a refutation.** Exit 0 means the proposition
   holds, exit 3 means a counterexample was exhibited, and any other non-zero
   code means the attempt could not decide.
"""

from __future__ import annotations

from dataclasses import dataclass
import re
from typing import Callable, Iterable, Sequence

from adaptive_harness.research.claim import (EXIT_COUNTEREXAMPLE, EXIT_HOLDS, ParsedClaim,
                                              Proposition, TopicPlan, collect_symbols)

# Header prepended to every generated script. It documents the exit-code
# contract inside the artifact itself, so a reader of proofs/ can adjudicate
# the script by hand.
_SCRIPT_HEADER = '''"""{statement}

Generated by the Adaptive Agent Harness derivation kernel (strategy: {strategy}).
Exit-code contract: {holds} = the proposition holds; {counter} = a counterexample
was exhibited; any other code = the attempt could not decide.
"""
import sys

# A user-supplied expression may name any SymPy object, so the whole namespace
# is imported rather than a hand-maintained list that would go stale.
from sympy import *
from sympy import powsimp, simplify

HOLD = {holds}
COUNTEREXAMPLE = {counter}


def canon(expr):
    """Canonicalize an exact expression before comparing it."""
    return simplify(powsimp(expr, force=True))


def hold(message):
    print(f"[HOLD] {{message}}")
    raise SystemExit(HOLD)


def refute(finding):
    print(f"[COUNTEREXAMPLE] {{finding}}")
    raise SystemExit(COUNTEREXAMPLE)


def undecided(reason):
    print(f"[UNDECIDED] {{reason}}")
    raise SystemExit(4)

'''


def _script(statement: str, strategy: str, body: str) -> str:
    return _SCRIPT_HEADER.format(statement=statement, strategy=strategy,
                                 holds=EXIT_HOLDS, counter=EXIT_COUNTEREXAMPLE) + body


# --- generic identity -----------------------------------------------------

_PY_TO_TYPST_MATH = (("**", "^"), ("*", " "), ("/", " slash "))


def to_typst_math(expression: str) -> str:
    """Render a Python-flavoured expression as Typst math markup.

    A supplied claim is written in SymPy syntax, which uses ``**`` for powers
    and ``*`` for products. Typst math uses ``^`` and juxtaposition, so a raw
    copy would not typeset; translating here keeps the paper readable without
    asking the operator to write Typst instead of SymPy.
    """
    text = str(expression)
    for python_token, typst_token in _PY_TO_TYPST_MATH:
        text = text.replace(python_token, typst_token)
    # "a slash b" is only valid inside frac(); use an inline fraction instead.
    if " slash " in text:
        left, _, right = text.partition(" slash ")
        text = f"frac({left.strip()}, {right.strip()})"
    return " ".join(text.split())


def identity_proposition(claim: ParsedClaim, prop_id: str = "PROP-01") -> Proposition:
    """Decide a user-supplied identity of the form ``lhs == rhs``.

    This is the general path: it places no restriction on what the expressions
    are, only on them being written in SymPy syntax with declared free symbols.

    Refutation requires an *exhibited* counterexample, not merely a failure to
    simplify to zero. "SymPy could not prove this" is not evidence of falsity,
    so a non-zero residual is only accepted as DISPROVEN once the script
    substitutes exact rational values and exhibits a point where the two sides
    differ. Otherwise the attempt reports INCONCLUSIVE.
    """
    if not claim.machine_checkable:
        raise ValueError("claim is not machine-checkable")
    # Built outside the template so the generated comprehension keeps real braces
    # instead of being interpolated at generation time.
    assignment = (", ".join(claim.symbols) + " = symbols('"
                  + " ".join(claim.symbols) + "')")
    symbol_tuple = ("(" + ", ".join(repr(name) for name in claim.symbols)
                    + ("," if len(claim.symbols) == 1 else "") + ")")
    setup = f"""
{assignment}
lhs = {claim.lhs}
rhs = {claim.rhs}

residual = canon(lhs - rhs)
print("residual =", residual)

if residual == 0:
    hold("lhs - rhs simplifies to exactly 0, so the identity holds identically")

# Not identically zero. To claim DISPROVEN we must exhibit an actual point.
# An unevaluated integral means the comparison is not decidable here, so we
# decline rather than guess.
if residual.has(Integral):
    undecided("the residual contains an unevaluated integral, so no verdict is possible")

# Exact rational probes, including negatives: sqrt(x^2) == x holds for x >= 0
# and fails for x < 0, so positive-only probes would miss the refutation.
probes = [Rational(0), Rational(1), Rational(-1), Rational(2), Rational(-2),
          Rational(1, 2), Rational(-1, 2), Rational(3), Rational(-3), Rational(5, 3)]
for point in probes:
    value = simplify(powsimp(residual.subs(dict.fromkeys({symbol_tuple}, point)), force=True))
    if value.is_number and value != 0:
        where = ", ".join(f"{{name}}={{point}}" for name in {symbol_tuple})
        refute(f"counterexample at {{where}}: lhs - rhs = {{value}} (nonzero)")

undecided("no exact rational probe exhibited a difference and the residual did "
          "not simplify to zero; the identity may still hold")
"""
    return Proposition(
        prop_id=prop_id, kind="identity",
        name="A supplied algebraic identity",
        hypotheses=("`" + "`, `".join(claim.symbols) + "` range over the reals or complexes as "
                    "declared; the identity is asserted for all of them.",),
        statement=(f"For all declared free symbols, "
                   f"${to_typst_math(claim.lhs)} = {to_typst_math(claim.rhs)}$."),
        display=(f"{to_typst_math(claim.lhs)} = {to_typst_math(claim.rhs)}",),
        proof_sketch="Both sides are exact symbolic expressions, so their difference is formed "
                     "in closed form and reduced to a canonical form. If it is identically zero "
                     "the identity holds for every assignment. If it is not, refutation requires "
                     "more than a failure to simplify: the script substitutes exact rational "
                     "values, including negative ones, and reports DISPROVEN only once some "
                     "assignment makes the difference a definite nonzero number. Any other "
                     "outcome is reported as undecided.",
        consequence="A supplied claim is settled by direct computation rather than by appeal to a "
                    "stored result.",
        notation=tuple((name, "a free symbol of the claim") for name in claim.symbols),
        script=_script(f"Identity {claim.lhs} == {claim.rhs}", "generic-identity", setup),
        rationale="Both sides were written as exact symbolic expressions. The identity is "
                  "accepted only if the difference reduces to exactly 0, and refuted only "
                  "if an exact rational witness makes it nonzero.")


