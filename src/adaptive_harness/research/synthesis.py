def _matches(topic: str, keywords: Iterable[str]) -> bool:
    lowered = (topic or "").lower()
    return any(keyword in lowered for keyword in keywords)


def plan_research(topic: str, claim: ParsedClaim | None = None) -> TopicPlan:
    """Decide what to attempt for a topic, and say so when nothing matches.

    Returning an explicit empty plan is important: a topic the kernel cannot
    formalise must produce an INCONCLUSIVE paper that names what it would need,
    not a confident-sounding paper about nothing.
    """
    notes: list[str] = []

    if claim is not None and claim.machine_checkable:
        try:
            return TopicPlan(topic=topic, strategy="generic-identity",
                             propositions=(identity_proposition(claim),),
                             notes="A checkable identity was supplied, so it was decided directly "
                                   "rather than through the topic library.")
        except ValueError as exc:  # pragma: no cover - guarded by machine_checkable
            notes.append(f"The supplied claim could not be formalised: {exc}")

    selected: list[Proposition] = []
    strategies: list[str] = []
    for builder in _LIBRARY:
        if _matches(topic, builder.keywords):
            strategies.append(builder.name)
            selected.extend(builder.build())
    if _matches(topic, _QUANTILE_BUILDER.keywords) and not any(
            item.kind == "identity" and "quantile" in item.statement.lower() for item in selected):
        strategies.append(_QUANTILE_BUILDER.name)
        selected.extend(_QUANTILE_BUILDER.build())

    if not selected:
        return TopicPlan(
            topic=topic, strategy="none", propositions=(),
            notes=("No derivation strategy matched this topic, so no proposition was constructed "
                   "and the claim was not tested. Supply a checkable claim as 'lhs == rhs' with "
                   "--symbols, or rephrase the topic using terms such as pareto, heavy-tailed, "
                   "critical index, balanced split, routing, or quantile."))
    if len(strategies) > 1:
        notes.append(f"Multiple strategies matched ({', '.join(strategies)}); all were attempted "
                     f"so that one refutation is enough to sink the claim.")
    return TopicPlan(topic=topic, strategy="+".join(strategies), propositions=tuple(selected),
                     notes=" ".join(notes))
