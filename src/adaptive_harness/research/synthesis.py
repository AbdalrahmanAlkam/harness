def plan_experiments(topic: str, seed: int = 20260926) -> tuple[tuple[Experiment, ...], str]:
    """Select the corroborating simulations for a topic, pinned to ``seed``."""
    selected: list[Experiment] = []
    strategies: list[str] = []
    for name, keywords, build in _EXPERIMENTS:
        if _matches(topic, keywords):
            strategies.append(name)
            selected.append(build(seed))
    notes = ("No corroborating simulation matched this topic, so the results stand on exact "
             "computation alone." if not selected else
             f"Corroborating simulations selected: {', '.join(strategies)}.")
    return tuple(selected), notes


