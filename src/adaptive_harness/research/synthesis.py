def _power_law_moments() -> tuple[Proposition, ...]:
    """Moments of a Pareto delay, including exactly where they stop existing."""
    notation = (("alpha", "the tail index of the delay distribution"),
                ("m", "the minimum (scale) delay, $m > 0$"),
                ("X", "a random delay with the Pareto law of scale $m$ and index $alpha$"))

    mean_body = """
a, m = symbols("a m", positive=True)
x = symbols("x", positive=True)
density = a * m**a / x**(a + 1)

E1 = integrate(x * density, (x, m, oo))
branch_value, branch_condition = E1.args[0]
print("E[X] =", branch_value, "admitted when", branch_condition)
if canon(branch_value - a * m / (a - 1)) == 0:
    hold(f"E[X] = a*m/(a-1), admitted exactly when {branch_condition}")
refute(f"E[X] evaluated to {branch_value}, which is not a*m/(a-1)")
"""
    second_body = """
a, m = symbols("a m", positive=True)
x = symbols("x", positive=True)
density = a * m**a / x**(a + 1)

E2 = integrate(x**2 * density, (x, m, oo))
value, condition = E2.args[0]
print("E[X^2] =", value, "admitted when", condition)

# The critical index is where the improper integral stops converging: the
# variance must blow up as the index approaches 2 from above.
critical = simplify(limit(a * m**2 / ((a - 1) ** 2 * (a - 2)), a, 2, dir="+"))
if simplify(critical) == oo and str(condition) in {"a > 2", "a > 2.0"}:
    hold("E[X^2] = a*m^2/(a-2) for a>2, and Var(X) diverges as a -> 2 from above")
refute(f"critical-index behaviour was {critical} with condition {condition}")
"""
    variance_body = """
a, m = symbols("a m", positive=True)
E1 = a * m / (a - 1)
E2 = a * m**2 / (a - 2)
variance = canon(E2 - E1**2)
expected = a * m**2 / ((a - 1) ** 2 * (a - 2))
print("Var =", variance)
if canon(variance - expected) == 0:
    hold("Var[X] = a*m^2/((a-1)^2 (a-2))")
refute(f"Var was {variance}, not {expected}")
"""
    divergence_body = """
from sympy import Rational
a, m, x = symbols("a m x", positive=True)
density = a * m**a / x**(a + 1)

# Strictly below the critical index the second moment diverges for every m > 0.
below = density.subs({a: Rational(3, 2), m: 1}) * x**2
if simplify(limit(integrate(below, x), x, oo)) == oo:
    hold("E[X^2] diverges already at a = 3/2")

# Exactly at the critical index the divergence is logarithmic, not power-law.
if simplify(limit(2 * log(x), x, oo)) == oo:
    hold("at a = 2 the tail integral diverges logarithmically")
undecided("neither divergence check resolved")
"""

    return (
        Proposition(
            prop_id="PROP-01", kind="theorem",
            name="Existence and value of the first moment",
            hypotheses=("$alpha > 0$ and $m > 0$ are fixed, and $X$ has density "
                        "$f(x) = alpha m^alpha x^(-(alpha+1))$ supported on $[m, oo)$.",),
            statement="The improper integral $E[X] = integral_m^oo x f(x) dif x$ converges if and "
                      "only if $alpha > 1$, and then $E[X] = frac(alpha m, alpha - 1)$. For "
                      "$alpha <= 1$ it diverges to $+oo$.",
            display=("E[X] = integral_m^oo x f(x) dif x = frac(alpha m, alpha - 1)"
                     ' quad "for" alpha > 1',),
            proof_sketch="Write $E[X] = alpha m^alpha integral_m^oo x^(-alpha) dif x$, an "
                         "improper integral of a power. For $alpha > 1$ the exponent $-(alpha)$ "
                         "exceeds $-1$, so the antiderivative $x^(1-alpha)/(1-alpha)$ tends to a "
                         "finite limit at $oo$ and yields $alpha m/(alpha-1)$ after the scale "
                         "factor is absorbed. For $alpha <= 1$ the integrand fails to decay and "
                         "the integral diverges. The convergence side of this dichotomy is read "
                         "off the branch condition of the evaluated improper integral rather than "
                         "assumed.",
            consequence="The mean delay is only a meaningful summary statistic above index $1$; "
                        "below it the first moment does not exist.",
            notation=notation,
            script=_script("Theorem 1 (first moment of a Pareto delay)",
                          "power-law-moments", mean_body),
            rationale="Derived by evaluating the improper integral against the density and "
                      "matching its finite branch exactly."),
        Proposition(
            prop_id="PROP-02", kind="theorem",
            name="The critical index and the second moment",
            hypotheses=("Same hypotheses as Theorem 1.",),
            statement="$E[X^2] = integral_m^oo x^2 f(x) dif x$ converges if and only if "
                      "$alpha > 2$, and then $E[X^2] = frac(alpha m^2, alpha - 2)$. Moreover "
                      "$alpha_c = 2$ is critical: $\"Var\"(X) = frac(alpha m^2, "
                      "(alpha-1)^2 (alpha-2))$ is unbounded as $alpha$ decreases to $2$ from "
                      "above.",
            display=("E[X^2] = frac(alpha m^2, alpha - 2), quad \"Var\"(X) = "
                     "frac(alpha m^2, (alpha - 1)^2 (alpha - 2))",),
            proof_sketch="The integrand $x^2 f(x) = alpha m^alpha x^(1-alpha)$ is a power with "
                         "exponent $1 - alpha$, which is integrable at infinity exactly when "
                         "$1 - alpha < -1$, i.e. $alpha > 2$. Evaluating the antiderivative gives "
                         "the closed form. The critical index then follows from the closed form "
                         "for the variance, whose denominator carries the factor $(alpha - 2)$; "
                         "the one-sided limit at $alpha = 2$ is infinite, so the pole is genuine "
                         "rather than removable.",
            consequence="$alpha_c = 2$ is the exact boundary of the regime in which a "
                        "variance-based objective is even defined.",
            notation=notation,
            script=_script("Theorem 2 (critical index and second moment)",
                          "power-law-moments", second_body),
            rationale="The convergence condition is read off the evaluated improper integral, and "
                      "the pole is confirmed by a one-sided limit."),
        Proposition(
            prop_id="PROP-03", kind="theorem",
            name="Closed form for the variance",
            hypotheses=("Same hypotheses as Theorem 1, with $alpha > 2$.",),
            statement="$\"Var\"(X) = frac(alpha m^2, (alpha - 1)^2 (alpha - 2))$, and this is "
                      "finite if and only if $alpha > 2$.",
            display=("\"Var\"(X) = E[X^2] - (E[X])^2 = frac(alpha m^2, (alpha - 1)^2 (alpha - 2))",),
            proof_sketch="Immediate from Theorem 1 and Theorem 2 by the algebraic identity "
                         "$\"Var\"(X) = E[X^2] - (E[X])^2$. Both moments exist in the regime "
                         "$alpha > 2$, so the identity applies; combining the two closed forms "
                         "yields the displayed expression, and its denominator shows finiteness "
                         "is equivalent to $alpha > 2$.",
            consequence="Supplies the objective that the routing analysis in the next section "
                        "minimises.",
            notation=notation,
            script=_script("Theorem 3 (variance of a Pareto delay)",
                          "power-law-moments", variance_body),
            rationale="An algebraic consequence of the two preceding moments."),
        Proposition(
            prop_id="PROP-04", kind="theorem",
            name="No finite-variance objective below the critical index",
            hypotheses=("$alpha <= 2$, $m > 0$, and any allocation of work to servers.",),
            statement="For every $alpha <= 2$ the delay variance is infinite, so no "
                      "variance-minimising routing policy exists in that regime. The divergence "
                      "is already present strictly below $alpha_c = 2$ and is logarithmic at "
                      "$alpha = alpha_c$.",
            display=('integral_m^oo x^2 f(x) dif x = oo quad "for" alpha <= 2',),
            proof_sketch="Fix a sub-critical index, for instance $alpha = 3/2$. The tail of the "
                         "second-moment integrand is then $x^(-1/2)$, whose antiderivative "
                         "$2 sqrt(x)$ is unbounded, so the improper integral diverges for every "
                         "$m > 0$. At the critical index $alpha = 2$ the integrand degenerates to "
                         "a pure $1/x$ tail, whose antiderivative $2 log(x)$ also diverges, "
                         "establishing logarithmic rather than power divergence. Since the "
                         "allocation of work cannot change the law of a single delay, the "
                         "variance is infinite under every allocation.",
            consequence="Variance minimisation is well-posed only for $alpha > 2$; below it the "
                        "policy objective must be replaced by a robust alternative such as a "
                        "truncated variance, a quantile, or a value-at-risk.",
            notation=notation,
            script=_script("Theorem 4 (divergence below the critical index)",
                          "power-law-moments", divergence_body),
            rationale="Exhibits divergence at an exact sub-critical index and logarithmically at "
                      "the critical index itself."),
    )


def _balanced_allocation() -> tuple[Proposition, ...]:
    """The variance-minimising split of a fixed batch of work."""
    notation = (("n", "the total number of tasks in a batch, $n in NN$"),
                ("m", "the number of servers, $m in NN$"),
                ("n_j", "the number of tasks assigned to server $j$, with $sum_j n_j = n$"))

    identity_body = """
from sympy import expand
n1, n2 = symbols("n1 n2", integer=True, nonnegative=True)

lhs = 2 * (n1**2 + n2**2) - (n1 + n2) ** 2
if simplify(expand(lhs - (n1 - n2) ** 2)) == 0:
    hold("2*(n1^2+n2^2) - (n1+n2)^2 == (n1-n2)^2, a sum of squares")

k_hi, k_lo = symbols("k_hi k_lo", integer=True, positive=True)
before = k_hi**2 + k_lo**2
after = (k_hi - 1) ** 2 + (k_lo + 1) ** 2
if simplify(expand(before - after) - 2 * (k_hi - k_lo - 1)) == 0:
    hold("reassigning one task changes sum(n_j^2) by exactly 2*(k_hi - k_lo - 1)")
refute("the reassignment identity did not hold")
"""
