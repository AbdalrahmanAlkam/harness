def ci95(samples):
    """Mean and a 95% half-width; the t-correction widens small samples."""
    values = np.asarray(samples, dtype=float)
    n = values.size
    mean = float(values.mean())
    if n < 2:
        return mean, 0.0
    stderr = float(values.std(ddof=1) / np.sqrt(n))
    t_table = {2: 12.706, 3: 4.303, 4: 3.182, 5: 2.776, 6: 2.571, 7: 2.447, 8: 2.365,
               9: 2.306, 10: 2.262, 12: 2.201, 15: 2.145, 20: 2.093, 25: 2.064, 30: 2.045}
    return mean, t_table.get(n, 1.96) * stderr


