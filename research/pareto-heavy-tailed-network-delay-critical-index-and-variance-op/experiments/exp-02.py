def ci95(samples):
    """Mean and a 95% half-width; the t-correction widens small samples."""
    values = np.asarray(samples, dtype=float)
    n = values.size
    mean = float(values.mean())
    if n < 2:
        return mean, 0.0
    stderr = float(values.std(ddof=1) / np.sqrt(n))
    t_table = {2: 12.706, 3: 4.303, 4: 3.182, 5: 2.776, 6: 2.571, 7: 2.447, 8: 2.365,
               9: 2.306, 10: 2.262, 12: 2.201, 15: 2.145, 20: 2.093, 25: 2.064, 30: 2.045}
    return mean, t_table.get(n, 1.96) * stderr


def write_csv(name, header, rows):
    import csv
    with open(name, "w", newline="") as handle:
        writer = csv.writer(handle)
        writer.writerow(header)
        writer.writerows(rows)


ALPHA, N_TASKS, N_SERVERS, N_TRIALS = 3, 601, 4, 300
rng = np.random.default_rng(SEED)
arrivals = rng.pareto(ALPHA, (N_TRIALS, N_TASKS)) + 1.0

base, remainder = divmod(N_TASKS, N_SERVERS)
SPLITS = {
    "balanced": tuple(base + (1 if j < remainder else 0) for j in range(N_SERVERS)),
    "moderate": (200, 150, 150, 101),
    "greedy": (N_TASKS,) + (0,) * (N_SERVERS - 1),
}
for name, counts in SPLITS.items():
    assert sum(counts) == N_TASKS and len(counts) == N_SERVERS

# The exact THM-06 excess for the balanced split is r*(m-r).
excess = N_SERVERS * sum(c ** 2 for c in SPLITS["balanced"]) - N_TASKS ** 2
if excess != remainder * (N_SERVERS - remainder):
    contradict(f"the imbalance excess was {excess}, not r*(m-r)")


def batch_variance(delays, counts):
    loads, cursor = [], 0
    for count in counts:
        loads.append(delays[cursor:cursor + count].sum())
        cursor += count
    return float(np.var(np.asarray(loads), ddof=1))


variances = {name: np.empty(N_TRIALS) for name in SPLITS}
for trial in range(N_TRIALS):
    for name, counts in SPLITS.items():
        variances[name][trial] = batch_variance(arrivals[trial], counts)

means = {name: float(v.mean()) for name, v in variances.items()}
print("empirical mean batch variance:", {k: round(v, 3) for k, v in means.items()})

# The falsifiable prediction is a rank order, not a magnitude: variance must
# increase with the theoretical imbalance quantity sum(n_j^2).
theory_order = sorted(SPLITS, key=lambda n: sum(c ** 2 for c in SPLITS[n]))
observed_order = sorted(SPLITS, key=lambda n: means[n])
print("theory order:", theory_order, "observed order:", observed_order)
if observed_order != theory_order:
    contradict(f"the empirical ordering {observed_order} contradicts the theory {theory_order}")

ratio = variances["moderate"] / variances["balanced"]
r_mean, r_half = ci95(ratio)
print(f"moderate/balanced = {r_mean:.4f} +/- {r_half:.4f}")
if r_mean - r_half <= 1.0:
    contradict("a 5% load imbalance was not measurably worse than the balanced split")

write_csv("empirical_data.csv", ["trial", "balanced", "moderate", "greedy"],
          [[i] + [f"{variances[n][i]:.10f}" for n in ("balanced", "moderate", "greedy")]
           for i in range(N_TRIALS)])
agree("the empirical variance ordering matches the theoretical imbalance ordering, "
      "and the paired interval excludes a ratio of 1")
